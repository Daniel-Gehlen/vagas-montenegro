    public function buscarVagasGoogle() {
        try {
            $this->logger->info("Iniciando busca de vagas no Google");

            $vagas = $this->buscarVagasReaisMontenegro();

            $vagasInseridas = 0;
            foreach ($vagas as $vaga) {
                if ($this->inserirVagaSeNaoExiste($vaga)) {
                    $vagasInseridas++;
                }
            }

            $this->logger->info("Busca concluída: {$vagasInseridas} novas vagas inseridas");

            http_response_code(200);
            echo json_encode([
                'sucesso' => true,
                'mensagem' => "Busca concluída: {$vagasInseridas} novas vagas inseridas",
                'total' => count($vagas)
            ]);
        } catch (Exception $e) {
            $this->logger->error("Erro na busca: " . $e->getMessage());
            http_response_code(500);
            echo json_encode(['sucesso' => false, 'erro' => $e->getMessage()]);
        }
    }

